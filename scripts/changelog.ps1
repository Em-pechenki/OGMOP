# Генерация CHANGELOG.md из conventional commits (git log).
# Запуск: pwsh scripts/changelog.ps1 [-Version "0.2.0"] [-SinceTag "v0.1.0"] [-OutputPath "CHANGELOG.md"]
param(
    [string]$Version = "",
    [string]$SinceTag = "",
    [string]$OutputPath = "CHANGELOG.md"
)

$ErrorActionPreference = "Stop"
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$OutputEncoding = [System.Text.Encoding]::UTF8
Set-Location (Split-Path -Parent $PSScriptRoot)

# Определяем базовый тег
if (-not $SinceTag) {
    try { $SinceTag = (git describe --tags --abbrev=0 2>$null) } catch { $SinceTag = "" }
}
if ($SinceTag) { $range = "$SinceTag..HEAD" } else { $range = "HEAD" }

# Получаем коммиты (hash + subject)
$raw = git -c i18n.logOutputEncoding=utf-8 log $range --pretty=format:"%H%x09%s" 2>$null
if (-not $raw) {
    Write-Host "Нет коммитов для changelog."
    exit 0
}

# Группировка по типам conventional commits
$groups = [ordered]@{
    "Breaking" = @()
    "Added"    = @()
    "Fixed"    = @()
    "Changed"  = @()
    "Docs"     = @()
    "Chore"    = @()
    "Other"    = @()
}

$seen = @{}
foreach ($line in ($raw -split "`n")) {
    $line = $line.Trim()
    if (-not $line) { continue }
    $parts = $line -split "`t", 2
    $hash = if ($parts.Count -gt 0) { $parts[0].Substring(0,7) } else { "" }
    $subject = if ($parts.Count -gt 1) { $parts[1] } else { "" }
    if (-not $subject) { continue }

    $type = ""
    $scope = ""
    $msg = $subject
    $breaking = $subject -match "!" -or $subject -match "BREAKING CHANGE"
    if ($subject -match "^(\w+)(\(([^)]+)\))?!?:\s*(.+)$") {
        $type = $Matches[1].ToLower()
        $scope = $Matches[3]
        $msg = $Matches[4]
    }
    if ($scope) { $msg = "**$scope**: $msg" }
    $entry = "- $msg ($hash)"
    if ($seen.ContainsKey($entry)) { continue }
    $seen[$entry] = $true

    if ($breaking) { $groups["Breaking"] += $entry; continue }
    switch ($type) {
        "feat"     { $groups["Added"] += $entry }
        "fix"      { $groups["Fixed"] += $entry }
        "refactor" { $groups["Changed"] += $entry }
        "perf"     { $groups["Changed"] += $entry }
        "docs"     { $groups["Docs"] += $entry }
        "chore"    { $groups["Chore"] += $entry }
        "ci"       { $groups["Chore"] += $entry }
        "build"    { $groups["Chore"] += $entry }
        "test"     { $groups["Chore"] += $entry }
        "style"    { $groups["Changed"] += $entry }
        default    { $groups["Other"] += $entry }
    }
}

# Собираем markdown
$sb = New-Object System.Text.StringBuilder
$sections = @("Breaking","Added","Fixed","Changed","Docs","Chore","Other")
foreach ($sec in $sections) {
    if ($groups[$sec].Count -gt 0) {
        [void]$sb.AppendLine("### $sec")
        foreach ($e in $groups[$sec]) { [void]$sb.AppendLine($e) }
        [void]$sb.AppendLine()
    }
}
$generated = $sb.ToString().TrimEnd()
if (-not $generated) {
    Write-Host "Нет изменений для changelog."
    exit 0
}

# Читаем текущий CHANGELOG
if (Test-Path $OutputPath) { $content = Get-Content $OutputPath -Raw -Encoding UTF8 } else { $content = "# Changelog`n`n" }

$today = Get-Date -Format "yyyy-MM-dd"
if ($Version) {
    $header = "## [$Version] - $today"
} else {
    $header = "## [Unreleased]"
}

# Заменяем секцию Unreleased (или добавляем)
if ($content -match "(?s)## \[Unreleased\].*?(?=\n## |\z)") {
    $newSection = "$header`n`n$generated`n`n"
    $content = [regex]::Replace($content, "(?s)## \[Unreleased\].*?(?=\n## |\z)", $newSection.TrimEnd(), 1)
} else {
    $content = $content -replace "(# Changelog[^\n]*\n)", "`$1`n$header`n`n$generated`n`n"
}

# Если указана версия — добавляем новый пустой Unreleased сверху
if ($Version) {
    $content = $content -replace "(# Changelog[^\n]*\n)", "`$1`n## [Unreleased]`n`n"
}

# Футер с датой генерации
if ($content -notmatch "Generated by scripts/changelog.ps1") {
    $content = $content.TrimEnd() + "`n`n---`n_Generated by scripts/changelog.ps1 on $today._`n"
}

Set-Content -Path $OutputPath -Value $content -Encoding UTF8
Write-Host "CHANGELOG.md обновлён ($header)."
Write-Host $generated
